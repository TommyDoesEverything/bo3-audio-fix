"""Generate the forwarding stubs for the proxy winmm.dll.

Reads the export table of the system winmm.dll and writes, into build/gen/:
  exports.h       export names (or ordinals) the DLL resolves at load time
  stubs.asm       one jump stub per export through g_real[]
  winmm.def       export table, with hooked names pointing at Hook_* functions

Usage: python tools/gen_exports.py [--debug]
--debug also routes the extra mixer calls through their logging hooks.
"""
import os
import sys

import pefile

ALWAYS = {"mixerGetNumDevs"}
DEBUG_ONLY = {
    "waveInGetNumDevs", "mixerOpen", "mixerGetDevCapsA", "mixerGetLineInfoA",
    "mixerGetLineControlsA", "mixerGetControlDetailsA", "mixerSetControlDetails",
}


def main() -> None:
    debug = "--debug" in sys.argv
    hooked = ALWAYS | (DEBUG_ONLY if debug else set())
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(root, "build", "gen-debug" if debug else "gen")
    os.makedirs(out, exist_ok=True)

    system = os.path.join(os.environ.get("SystemRoot", r"C:\Windows"), "System32", "winmm.dll")
    pe = pefile.PE(system)
    syms = sorted(pe.DIRECTORY_ENTRY_EXPORT.symbols, key=lambda e: e.ordinal)

    asm = ["; generated by tools/gen_exports.py", "EXTERN g_real:QWORD", ".code"]
    deff = ["LIBRARY winmm", "EXPORTS"]
    names = []
    for i, e in enumerate(syms):
        name = e.name.decode() if e.name else None
        names.append(name if name else f"#{e.ordinal}")
        if name in hooked:
            deff.append(f"  {name}=Hook_{name} @{e.ordinal}")
            continue
        asm += [f"Stub_{i} PROC", f"  jmp QWORD PTR [g_real+{i * 8}]", f"Stub_{i} ENDP"]
        if name:
            deff.append(f"  {name}=Stub_{i} @{e.ordinal}")
        else:
            deff.append(f"  Ord{e.ordinal}=Stub_{i} @{e.ordinal} NONAME")
    asm.append("END")

    with open(os.path.join(out, "stubs.asm"), "w") as f:
        f.write("\n".join(asm) + "\n")
    with open(os.path.join(out, "winmm.def"), "w") as f:
        f.write("\n".join(deff) + "\n")
    with open(os.path.join(out, "exports.h"), "w") as f:
        f.write(f"#define EXPORT_COUNT {len(names)}\nstatic const char* g_names[EXPORT_COUNT] = {{\n")
        for n in names:
            if n.startswith("#"):
                f.write(f"  (const char*)(ULONG_PTR){n[1:]},\n")
            else:
                f.write(f'  "{n}",\n')
        f.write("};\n")
    print(f"{len(names)} exports, {len(hooked)} hooked -> {out}")


if __name__ == "__main__":
    main()
